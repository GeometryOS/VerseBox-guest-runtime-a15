#!/bin/sh
# Build the A15 "host-devices" program: the HALs the Redroid 15 image expects
# but does not ship a service for.
#
# Currently three HALs (all AIDL, all "default"):
#   android.hardware.vibrator   IVibrator + IVibratorManager, version 2
#   android.hardware.sensors    ISensors, version 2 (empty sensor list)
#   android.hardware.thermal    IThermal, version 3 (empty temperatures)
#
# Why AIDL and not HIDL:
#   * the image's frameworks/base/libs/vibratorservice connects to the AIDL HAL
#     first and only falls back to V1_0::IVibrator::getService() -- which blocks
#     forever -- when AServiceManager_isDeclared() says the AIDL HAL is absent
#     (disassembly recorded in docs/android15-port/12 and in the source header);
#   * the image exports the AIDL service-side classes
#     (rootfs/system/lib64/android.hardware.vibrator-V3-ndk.so: BnVibrator,
#     BnVibratorManager), so the implementation links the ROM library instead of
#     carrying a copy of the interface;
#   * a HIDL server would need headers generated by hidl-gen from
#     hardware/interfaces, and neither the generator nor the interface tree
#     exists in this workspace.
#
# The .aidl declarations under vendor/hidl/aidl are the AOSP
# android-15.0.0_r36 sources (provenance: vendor/hidl/sources.sha256); the
# headers under $OUT/generated/aidl are build intermediates and are regenerated
# by $AIDL on every clean build, never edited by hand.
set -eu
: "${MODULE:=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)}"
. "$(dirname -- "$0")/compile.sh"

# aidl comes from the Android SDK build-tools. Probe PATH first (CI exports it),
# then the two build-tools versions this project has used, with/without .exe.
case "$(uname -s 2>/dev/null || echo Linux)" in
    MINGW*|MSYS*|CYGWIN*) AIDL_EXE=.exe ;;
    *) AIDL_EXE= ;;
esac
SDK_PATH=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-C:/Users/22437/AppData/Local/Android/Sdk}}
if [ -z "${AIDL:-}" ]; then
    AIDL=$(command -v aidl 2>/dev/null || true)
fi
for candidate in "$AIDL" "$SDK_PATH/build-tools/36.0.0/aidl$AIDL_EXE" "$SDK_PATH/build-tools/35.0.0/aidl$AIDL_EXE"; do
    if [ -n "$candidate" ] && [ -x "$candidate" ]; then AIDL=$candidate; break; fi
done
: "${AIDL:=}"
AIDL_SRC="$MODULE/vendor/hidl/aidl"
AIDL_OUT="$OUT/generated/aidl"
NDK_HDR="$MODULE/vendor/hidl/ndk"
IMG="$MODULE/rootfs/system/lib64"

OBJ="$OUT/obj/host-hal"
mkdir -p "$OBJ" "$OUT/bin" "$AIDL_OUT"
test -f "$RT/build/lib/libc.so" || { echo "run build-libc.sh first" >&2; exit 1; }
test -x "$AIDL" || { echo "aidl compiler not found: $AIDL (set AIDL=...)" >&2; exit 1; }
test -f "$IMG/android.hardware.vibrator-V3-ndk.so" || { echo "missing A15 vibrator AIDL lib" >&2; exit 1; }
test -f "$IMG/android.hardware.thermal-V3-ndk.so" || { echo "missing A15 thermal AIDL lib" >&2; exit 1; }

# 1. Generate the AIDL NDK headers (build intermediate, never hand-edited).
for aidl in "$AIDL_SRC/android/os/PersistableBundle.aidl" \
             "$AIDL_SRC/android/hardware/vibrator/IVibrator.aidl" \
             "$AIDL_SRC/android/hardware/vibrator/IVibratorManager.aidl" \
             "$AIDL_SRC/android/hardware/sensors/ISensors.aidl" \
             "$AIDL_SRC/android/hardware/thermal/IThermal.aidl"; do
    test -f "$aidl" || { echo "missing AIDL source: $aidl" >&2; exit 1; }
done
# aidl is a native Windows binary and compares the input path against its import
# roots as plain strings after appending a backslash to the root, so every
# argument must use the Windows backslash form. Git Bash would convert them a
# second time, hence MSYS2_ARG_CONV_EXCL.
win() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }
SRC_W=$(win "$AIDL_SRC")
OUT_W=$(win "$AIDL_OUT")
# Every .aidl in the package is compiled: the generated interface headers include
# the parcelable headers (Braking.h, Effect.h, ...), and aidl emits one header
# per input, so listing only the two interfaces is not enough.
aidl_inputs="$SRC_W\\android\\os\\PersistableBundle.aidl"
for src in "$AIDL_SRC"/android/hardware/vibrator/*.aidl \
           "$AIDL_SRC"/android/hardware/sensors/*.aidl \
           "$AIDL_SRC"/android/hardware/thermal/*.aidl \
           "$AIDL_SRC"/android/hardware/common/*.aidl \
           "$AIDL_SRC"/android/hardware/common/fmq/*.aidl; do
    aidl_inputs="$aidl_inputs $(win "$src")"
done
# --min_sdk_version=35: VibrationSessionConfig uses ParcelableHolder (API 31+).
MSYS2_ARG_CONV_EXCL='*' "$AIDL" --lang=ndk --structured --stability=vintf -v 3 --min_sdk_version=35 \
    -I"$SRC_W" -h"$OUT_W" -o"$OUT_W" $aidl_inputs

crt_pie
builtins=$(clang --target=$TARGET --print-libgcc-file-name)

# 2. Compile against the AIDL NDK headers. include_ndk/include_cpp/
#    include_platform are the AOSP r36 binder NDK headers: the NDK sysroot only
#    ships the C API (binder_ibinder.h / binder_parcel.h / binder_status.h), the
#    C++ ndk:: wrappers and the servicemanager/process entry points are platform
#    headers. They are vendored with hashes for that reason.
platform_compile "$MODULE/vendor/native/HostDevicesA15.cpp" "$OBJ/host-devices-a15.o" \
    -I"$AIDL_OUT" -I"$NDK_HDR/include_ndk" -I"$NDK_HDR/include_cpp" -I"$NDK_HDR/include_platform"

# 3. Link as a guest PIE against the ROM's binder/AIDL libraries. Everything it
#    needs at run time lives in the instance's vm/lib (the image libraries are
#    staged there with their real sonames).
ld.lld -pie -e _start -dynamic-linker /system/bin/linker64 \
    -z now -z relro -z max-page-size=4096 --no-undefined --exclude-libs ALL \
    "$OUT/obj/crt/crtbegin.o" "$OBJ/host-devices-a15.o" \
    "$IMG/libbinder_ndk.so" "$IMG/android.hardware.vibrator-V3-ndk.so" \
    "$IMG/android.hardware.sensors-V3-ndk.so" \
    "$IMG/android.hardware.thermal-V3-ndk.so" \
    "$IMG/android.hardware.common-V2-ndk.so" "$IMG/android.hardware.common.fmq-V1-ndk.so" \
    "$IMG/libbase.so" "$IMG/liblog.so" "$IMG/libutils.so" "$IMG/libcutils.so" \
    "$LIBCXX" "$LIBC" "$LIBM" "$LIBDL" "$LINKER" "$builtins" \
    "$OUT/obj/crt/crtend.o" -o "$OUT/bin/host-devices"
llvm-readelf -hlWd "$OUT/bin/host-devices" > "$OUT/bin/host-devices.elf.txt"
echo "host-hal: $OUT/bin/host-devices"
